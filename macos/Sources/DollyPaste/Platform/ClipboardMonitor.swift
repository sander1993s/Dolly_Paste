import AppKit

enum CapturedPayload {
    case text(String)
    case image(Data)
}

/// Main-thread-only pasteboard observer; never simulates keys or reads focused controls.
final class ClipboardMonitor {
    static let maxTextLength = 32_768
    static let ownCopyType = NSPasteboard.PasteboardType("be.dollypaste.own-copy")
    static let excludedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("org.nspasteboard.ConfidentialType"),
        .init("com.agilebits.onepassword"),
        ownCopyType
    ]

    var isPaused = false {
        didSet {
            // Starting or resuming never imports a clipboard value seen while paused.
            lastChangeCount = pasteboard.changeCount
        }
    }
    private let pasteboard: NSPasteboard
    private let onCapture: (CapturedPayload) -> Void
    private var lastChangeCount: Int
    private var timer: Timer?

    convenience init(onCapture: @escaping (CapturedPayload) -> Void) {
        self.init(pasteboard: .general, onCapture: onCapture)
    }

    // A named pasteboard lets tests avoid reading or changing the user's clipboard.
    init(pasteboard: NSPasteboard, onCapture: @escaping (CapturedPayload) -> Void) {
        self.pasteboard = pasteboard
        self.onCapture = onCapture
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        precondition(Thread.isMainThread)
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        timer.tolerance = 0.08
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    deinit { timer?.invalidate() }

    func poll() {
        precondition(Thread.isMainThread)
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard !isPaused else { return }

        let items = pasteboard.pasteboardItems ?? []
        let types = Set(items.flatMap(\.types)).union(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.excludedTypes),
              !types.contains(.fileURL),
              !types.contains(.init("NSFilenamesPboardType")) else { return }

        var payload: CapturedPayload?
        // Never substitute the textual description of a rejected image.
        if types.contains(.png) || types.contains(.tiff) {
            for type in [NSPasteboard.PasteboardType.png, .tiff] where types.contains(type) {
                if let bytes = pasteboard.data(forType: type),
                   let png = ImagePayload.normalizedPNG(from: bytes) {
                    payload = .image(png)
                    break
                }
            }
        } else if let text = pasteboard.string(forType: .string),
                  !text.isEmpty, text.utf16.count <= Self.maxTextLength {
            payload = .text(text)
        }
        // NSPasteboard does not offer a read lock. Discard a torn snapshot.
        guard pasteboard.changeCount == changeCount, let payload else { return }
        onCapture(payload)
    }

    func copyText(_ text: String) throws {
        precondition(Thread.isMainThread)
        // Image base64 is a supported copy action and may exceed capture's text limit.
        guard !text.isEmpty, text.utf8.count <= 4 * 1024 * 1024 else {
            throw ClipboardError.invalidPayload
        }
        let item = NSPasteboardItem()
        guard item.setString(text, forType: .string),
              item.setData(Data(), forType: Self.ownCopyType) else {
            throw ClipboardError.writeFailed
        }
        try write(item)
    }

    func copyImage(_ data: Data) throws {
        precondition(Thread.isMainThread)
        guard let png = ImagePayload.normalizedPNG(from: data) else {
            throw ClipboardError.invalidPayload
        }
        // Include TIFF for applications that do not consume public.png. Prepare
        // both representations before replacing the clipboard.
        guard let bitmap = NSBitmapImageRep(data: png),
              let tiff = bitmap.tiffRepresentation else { throw ClipboardError.invalidPayload }
        let originalIsPNG = data.count <= ImagePayload.maxPNGBytes &&
            data.starts(with: [137, 80, 78, 71, 13, 10, 26, 10])
        let item = NSPasteboardItem()
        guard item.setData(originalIsPNG ? data : png, forType: .png),
              item.setData(tiff, forType: .tiff),
              item.setData(Data(), forType: Self.ownCopyType) else {
            throw ClipboardError.writeFailed
        }
        try write(item)
    }

    private func write(_ item: NSPasteboardItem) throws {
        // Public AppKit API prevents these copies from entering Universal Clipboard.
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        defer { lastChangeCount = pasteboard.changeCount }
        guard pasteboard.writeObjects([item]) else { throw ClipboardError.writeFailed }
    }
}

enum ClipboardError: LocalizedError {
    case invalidPayload, writeFailed
    var errorDescription: String? {
        switch self {
        case .invalidPayload: return "This clip is empty, too large, or is not a valid image."
        case .writeFailed: return "macOS could not update the clipboard. Please try again."
        }
    }
}
